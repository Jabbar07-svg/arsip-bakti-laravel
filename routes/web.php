Route::get('/', fn () => redirect()->route(Auth::check() ? RolePermissions::landingRouteName(Auth::user()) : 'login'));
Route::redirect('/legacy', config('app.legacy_url').'/login.php')->name('legacy.login');
Route::get('/reset-password/{token}', [PasswordResetController::class, 'create'])->name('password.reset');
Route::post('/reset-password/{token}', [PasswordResetController::class, 'store'])->middleware('throttle:5,1')->name('password.reset.store');

Route::middleware('guest')->group(function (): void {
    Route::get('/login', [AuthController::class, 'create'])->name('login');
    Route::post('/login', [AuthController::class, 'store'])->middleware('throttle:5,1')->name('login.store');
});

